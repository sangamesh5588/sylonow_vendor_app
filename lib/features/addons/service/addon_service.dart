import 'package:riverpod_annotation/riverpod_annotation.dart';
import '../../../core/config/supabase_config.dart';
import '../models/addon.dart';

part 'addon_service.g.dart';

@riverpod
AddonService addonService(AddonServiceRef ref) {
  return AddonService();
}

class AddonService {
  final _client = SupabaseConfig.client;

  // Get all add-ons for the current vendor
  Future<List<Addon>> getVendorAddons() async {
    try {
// TODO: Replace with proper logging - print('🔍 DEBUG: Fetching vendor add-ons');
      
      // Get current vendor ID first
      final vendorId = await _getCurrentVendorId();
// TODO: Replace with proper logging - print('🔍 DEBUG: Current vendor ID: $vendorId');
      
      final response = await _client
          .from('add_ons')
          .select('*')
          .eq('vendor_id', vendorId)
          .order('created_at', ascending: false);

// TODO: Replace with proper logging - print('🔍 DEBUG: Add-ons response: $response');

      if (response.isEmpty) {
        return [];
      }

      return response
          .map<Addon>((data) => Addon.fromJson(data))
          .toList();
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to fetch vendor add-ons: $e');
      rethrow;
    }
  }

  // Get add-ons by category
  Future<List<Addon>> getAddonsByCategory(String category) async {
    try {
// TODO: Replace with proper logging - print('🔍 DEBUG: Fetching add-ons for category: $category');
      
      final response = await _client
          .from('add_ons')
          .select('*')
          .eq('category', category)
          .eq('is_active', true)
          .order('name', ascending: true);

// TODO: Replace with proper logging - print('🔍 DEBUG: Category add-ons response: $response');

      if (response.isEmpty) {
        return [];
      }

      return response
          .map<Addon>((data) => Addon.fromJson(data))
          .toList();
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to fetch add-ons by category: $e');
      rethrow;
    }
  }

  // Create a new add-on
  Future<Addon> createAddon(Addon addon) async {
    try {
      final addonData = addon.toJson();

      // Remove fields that should not be sent on creation (auto-generated by DB)
      addonData.remove('id');
      addonData.remove('created_at');
      addonData.remove('updated_at');

      // Get vendor ID from the current user
      final vendorId = await _getCurrentVendorId();
      addonData['vendor_id'] = vendorId;

      // Get theater ID for this vendor (if they have a theater)
      final theaterId = await _getVendorTheaterId();
      if (theaterId != null) {
        addonData['theater_id'] = theaterId;
      }

// TODO: Replace with proper logging - print('🔍 DEBUG: Creating add-on: $addonData');

      final response = await _client
          .from('add_ons')
          .insert(addonData)
          .select()
          .single();

// TODO: Replace with proper logging - print('🔍 DEBUG: Created add-on response: $response');
      return Addon.fromJson(response);
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to create add-on: $e');
      rethrow;
    }
  }

  // Update add-on
  Future<Addon> updateAddon(String addonId, Map<String, dynamic> updates) async {
    try {
// TODO: Replace with proper logging - print('🔍 DEBUG: Updating add-on $addonId with: $updates');
      
      final response = await _client
          .from('add_ons')
          .update(updates)
          .eq('id', addonId)
          .select()
          .single();

// TODO: Replace with proper logging - print('🔍 DEBUG: Updated add-on response: $response');
      return Addon.fromJson(response);
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to update add-on: $e');
      rethrow;
    }
  }

  // Delete add-on
  Future<void> deleteAddon(String addonId) async {
    try {
// TODO: Replace with proper logging - print('🔍 DEBUG: Deleting add-on: $addonId');
      
      await _client
          .from('add_ons')
          .delete()
          .eq('id', addonId);

// TODO: Replace with proper logging - print('🔍 DEBUG: Add-on deleted successfully');
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to delete add-on: $e');
      rethrow;
    }
  }

  // Toggle add-on active status
  Future<Addon> toggleAddonStatus(String addonId, bool isActive) async {
    try {
      return await updateAddon(addonId, {'is_active': isActive});
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to toggle add-on status: $e');
      rethrow;
    }
  }

  // Get available categories
  Future<List<String>> getAvailableCategories() async {
    try {
      // Return predefined categories instead of querying database
      // This ensures categories are always available even for new vendors
      final predefinedCategories = [
        'cake',
        'special service', 
        'extra-special-service',
        'cakes',
      ];
      
      // Also fetch any custom categories from the database
      final response = await _client
          .from('add_ons')
          .select('category')
          .not('category', 'is', null);

      final dbCategories = response
          .map<String>((data) => (data['category'] as String?) ?? '')
          .where((category) => category.isNotEmpty && !predefinedCategories.contains(category))
          .toSet()
          .toList();
      
      // Combine predefined and database categories
      final allCategories = [...predefinedCategories, ...dbCategories];
      allCategories.sort();
      return allCategories;
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to fetch categories: $e');
      // Return predefined categories as fallback
      return [
        'cake',
        'special service',
        'extra-special-service', 
        'cakes',
      ];
    }
  }

  // Helper method to get current vendor ID
  Future<String> _getCurrentVendorId() async {
    try {
      final user = _client.auth.currentUser;
      if (user == null) {
        throw Exception('User not authenticated');
      }

      final response = await _client
          .from('vendors')
          .select('id')
          .eq('auth_user_id', user.id)
          .single();

      return response['id'] as String;
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to get vendor ID: $e');
      rethrow;
    }
  }

  // Helper method to get vendor's theater ID
  Future<String?> _getVendorTheaterId() async {
    try {
      final user = _client.auth.currentUser;
      if (user == null) {
        return null;
      }

      // Get the vendor's theater (if they have one)
      // Note: private_theaters table uses 'owner_id' column for the vendor's auth user ID
      final response = await _client
          .from('private_theaters')
          .select('id')
          .eq('owner_id', user.id)
          .limit(1)
          .maybeSingle();

      if (response == null) {
        return null;
      }

      return response['id'] as String?;
    } catch (e) {
// TODO: Replace with proper logging - print('🔴 ERROR: Failed to get vendor theater ID: $e');
      return null;
    }
  }
}